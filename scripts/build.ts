import { parse } from 'yaml';
import { validateContent } from '../src/content/AssessmentContent.ts';
import interfaceYaml from '../content/interface.yaml';
import ontologyYaml from '../content/ontology.yaml';
import profilesYaml from '../content/profiles.yaml';
import questionsYaml from '../content/questions.yaml';

const readYaml = async (path: string): Promise<unknown> =>
  parse(await Bun.file(path).text());

const build = async (): Promise<void> => {
  const content = validateContent({
    ontology: await readYaml(ontologyYaml),
    questions: await readYaml(questionsYaml),
    profiles: await readYaml(profilesYaml),
    interface: await readYaml(interfaceYaml),
  });

  await Bun.write(
    'src/generated/content.ts',
    `// Generated by scripts/build.ts. Do not edit; edit content/*.yaml instead.\nexport default ${JSON.stringify(content, null, 2)} as const;\n`,
  );

  for await (const path of new Bun.Glob('dist/**/*').scan())
    await Bun.file(path).delete();

  const result = await Bun.build({
    entrypoints: ['index.html'],
    outdir: 'dist',
    target: 'browser',
    naming: '[name].[ext]',
    external: ['*.webmanifest', '*.svg'],
  });
  if (!result.success) throw new AggregateError(result.logs, 'Build failed');

  for (const path of ['manifest.webmanifest', 'icon.svg'])
    await Bun.write(`dist/${path}`, Bun.file(path));

  const files = await Array.fromAsync(new Bun.Glob('dist/**/*').scan());
  const fingerprint = new Bun.CryptoHasher('sha256');
  for (const path of files.sort()) fingerprint.update(await Bun.file(path).arrayBuffer());
  const version = fingerprint.digest('hex').slice(0, 12);
  const assets = files.map(path => `./${path.replace(/^dist\//, '')}`);
  const worker = (await Bun.file('service-worker.js').text())
    .replace('__BUILD__', version)
    .replace('__ASSETS__', JSON.stringify(['./', ...assets]));
  await Bun.write('dist/service-worker.js', worker);

  console.log(`Built AI Fitness ${content.ontology.version} from YAML (${version}).`);
};

if (import.meta.main) await build();
export { build };
